"""Generate dctl/FilmLab.dctl from fits.json (push/pull x interlayer development models per stock)."""
import json
import sys
from pathlib import Path

fits = json.loads(Path(sys.argv[1]).read_text())
out = Path(sys.argv[2])
stocks = ["kodak_vision3_50d", "kodak_vision3_200t", "kodak_vision3_250d", "kodak_vision3_500t"]
knots = fits["knots"]
push_levels = fits["push_levels"]
inter_levels = fits["interlayer_levels"]
nk = len(knots)

w, b, mid = [], [], []
for s in stocks:
    st = fits["stocks"][s]
    mid += st["mid"]
    for row in st["grid"]:
        for m in row:
            for c in range(3):
                w += m["w"][c]
                b += m["b"][c]


def arr(name, vals):
    body = ",\n    ".join(", ".join(f"{v:.5f}f" for v in vals[i:i + 12]) for i in range(0, len(vals), 12))
    return f"__CONSTANT__ float {name}[{len(vals)}] = {{\n    {body}\n}};\n"


src = f"""// FilmLab: negative development + printer lights, between a film LUT and a print LUT (spektrafilm, fixed wire).
// Node A: <stock>_film.cube -> Node B: this DCTL -> Node C: <stock>_<print>_print_<output>.cube
// Pick the same stock here as in the LUTs. Generated by scripts/build_dctl.py from fits.json; do not edit by hand.
//
// Push/Pull: per-layer development contrast fitted to the spektrafilm simulation (Kodak: push builds contrast most in
//   the cyan and magenta layers -> warm highlights / blue shadows), re-timed so mid-grey stays put.
// Interlayer: DIR-coupler interlayer inhibition, 1 = stock, 0 = none (less saturated), 1.5 = strong.
// Bleach Bypass: retained silver adds neutral density in proportion to developed density (re-timed at mid-grey).
// Printer points: 1 point = 0.025 log exposure; more light in a channel = less of that colour on the print.

DEFINE_UI_PARAMS(stock, Film Stock, DCTLUI_COMBO_BOX, 3, {{V50D, V200T, V250D, V500T}}, {{Vision3 50D 5203, Vision3 200T 5213, Vision3 250D 5207, Vision3 500T 5219}})
DEFINE_UI_PARAMS(push, Push / Pull (stops), DCTLUI_SLIDER_FLOAT, 0.0, {push_levels[0]:.1f}, {push_levels[-1]:.1f}, 0.1)
DEFINE_UI_PARAMS(inter, Interlayer, DCTLUI_SLIDER_FLOAT, 1.0, {inter_levels[0]:.1f}, {inter_levels[-1]:.1f}, 0.05)
DEFINE_UI_PARAMS(bleach, Bleach Bypass, DCTLUI_SLIDER_FLOAT, 0.0, 0.0, 1.0, 0.01)
DEFINE_UI_PARAMS(master, Printer Density, DCTLUI_SLIDER_FLOAT, 0.0, -24.0, 24.0, 0.5)
DEFINE_UI_PARAMS(red, Printer Red, DCTLUI_SLIDER_FLOAT, 0.0, -24.0, 24.0, 0.5)
DEFINE_UI_PARAMS(green, Printer Green, DCTLUI_SLIDER_FLOAT, 0.0, -24.0, 24.0, 0.5)
DEFINE_UI_PARAMS(blue, Printer Blue, DCTLUI_SLIDER_FLOAT, 0.0, -24.0, 24.0, 0.5)

#define D_MIN (-0.2f)
#define D_RANGE (4.2f)
#define NK {nk}
#define K0 ({knots[0]:.4f}f)
#define KSTEP ({knots[1] - knots[0]:.4f}f)
#define NP {len(push_levels)}
#define NI {len(inter_levels)}
#define SILVER 0.6f

{arr("PUSH_LV", push_levels)}{arr("INTER_LV", inter_levels)}{arr("MID", mid)}{arr("W", w)}{arr("B", b)}
__DEVICE__ float model_channel(int s, int pi, int ii, int c, float3 d, float3 m) {{
    int base = ((s * NP + pi) * NI + ii) * 3 + c;
    float dc = c == 0 ? d.x : (c == 1 ? d.y : d.z);
    float x = _clampf((dc - K0) / KSTEP, 0.0f, NK - 1.0f);
    int k = (int)_floorf(x);
    if (k > NK - 2) k = NK - 2;
    float t = x - k;
    float v = W[base * NK + k] * (1.0f - t) + W[base * NK + k + 1] * t;
    float o0 = c == 0 ? d.y - m.y : d.x - m.x;
    float o1 = c == 2 ? d.y - m.y : d.z - m.z;
    return v + B[base * 2] * o0 + B[base * 2 + 1] * o1;
}}

__DEVICE__ int segment(__CONSTANTREF__ float* lv, int n, float v) {{
    int i = 0;
    for (int j = 0; j < n - 1; j++) if (v >= lv[j]) i = j;
    return i;
}}

__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B) {{
    float3 d = make_float3(p_R * D_RANGE + D_MIN, p_G * D_RANGE + D_MIN, p_B * D_RANGE + D_MIN);
    float3 m = make_float3(MID[stock * 3], MID[stock * 3 + 1], MID[stock * 3 + 2]);

    float pv = _clampf(push, PUSH_LV[0], PUSH_LV[NP - 1]);
    float iv = _clampf(inter, INTER_LV[0], INTER_LV[NI - 1]);
    int pi = segment(PUSH_LV, NP, pv);
    int ii = segment(INTER_LV, NI, iv);
    float tp = (pv - PUSH_LV[pi]) / (PUSH_LV[pi + 1] - PUSH_LV[pi]);
    float ti = (iv - INTER_LV[ii]) / (INTER_LV[ii + 1] - INTER_LV[ii]);

    float out[3];
    for (int c = 0; c < 3; c++) {{
        out[c] = (1.0f - tp) * (1.0f - ti) * model_channel(stock, pi, ii, c, d, m)
               + tp * (1.0f - ti) * model_channel(stock, pi + 1, ii, c, d, m)
               + (1.0f - tp) * ti * model_channel(stock, pi, ii + 1, c, d, m)
               + tp * ti * model_channel(stock, pi + 1, ii + 1, c, d, m);
    }}

    float silver = bleach * SILVER * ((out[0] + out[1] + out[2]) - (m.x + m.y + m.z)) / 3.0f;
    float step = 0.025f;
    float r = out[0] + silver - (master + red) * step;
    float g = out[1] + silver - (master + green) * step;
    float b = out[2] + silver - (master + blue) * step;
    return make_float3((r - D_MIN) / D_RANGE, (g - D_MIN) / D_RANGE, (b - D_MIN) / D_RANGE);
}}
"""
out.write_text(src)
print(f"wrote {out} ({len(w) + len(b)} coefficients)")
